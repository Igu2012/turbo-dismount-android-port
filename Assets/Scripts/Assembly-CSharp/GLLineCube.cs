	private void RenderGLLines()
	{
		if ((bool)lineMaterial)
		{
			GL.PushMatrix();
			GL.MultMatrix(base.transform.localToWorldMatrix);
			lineMaterial.SetPass(0);
			GL.Color(new Color(1f, 1f, 1f, 1f));
			GL.Begin(1);
			for (int i = 0; i < lines.Length; i += 2)
			{
				GL.Vertex(lines[i]);
				GL.Vertex(lines[i + 1]);
			}
			GL.End();
			lineMaterial.SetPass(1);
			GL.Begin(1);
			for (int j = 0; j < lines.Length; j += 2)
			{
				GL.Vertex(lines[j]);
				GL.Vertex(lines[j + 1]);
			}
			GL.End();
			GL.PopMatrix();
		}
	}
